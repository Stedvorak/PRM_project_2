#!/usr/bin/env python3
"""
scripts/train.py

Feature Extraction, Model Training, and Pure C++ Header Export
for PRM Project 2 (Real-Time AI On-Device Classifier).

Contract:
- 4 States: 0=calm, 1=fast, 2=unattached, 3=shaking
- 10 Features (f[10]):
  0: acc_mag_std       (std of accel magnitude)
  1: acc_mag_range     (range of accel magnitude)
  2: gyro_mag_std      (std of gyro magnitude)
  3: gyro_mag_range    (range of gyro magnitude)
  4: var_ax            (variance of ax)
  5: var_ay            (variance of ay)
  6: var_az            (variance of az)
  7: mean_ax           (mean of ax)
  8: mean_az           (mean of az)
  9: log_var_acc_mag   (log of variance of accel magnitude)
- Pure C++ header: firmware/include/model.h
  int predict_sensor_state(const float f[10], float probs[4])
"""

import os
import glob
import json
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score

STATE_MAP = {
    'calm': 0,
    'fast': 1,
    'unattached': 2,
    'shaking': 3
}

STATE_NAMES = ["calm", "fast", "unattached", "shaking"]
FEATURE_NAMES = [
    "acc_mag_std",
    "acc_mag_range",
    "gyro_mag_std",
    "gyro_mag_range",
    "var_ax",
    "var_ay",
    "var_az",
    "mean_ax",
    "mean_az",
    "log_var_acc_mag"
]

WINDOW_SAMPLES = 100   # 100 samples = 2.0s at 50 Hz
STEP_SAMPLES = 25      # 25 samples = 0.5s at 50 Hz

def extract_features_from_window(w_ax, w_ay, w_az, w_gx, w_gy, w_gz):
    acc_mag = np.sqrt(w_ax**2 + w_ay**2 + w_az**2)
    gyro_mag = np.sqrt(w_gx**2 + w_gy**2 + w_gz**2)

    f0 = float(np.std(acc_mag))
    f1 = float(np.ptp(acc_mag))
    f2 = float(np.std(gyro_mag))
    f3 = float(np.ptp(gyro_mag))
    f4 = float(np.var(w_ax))
    f5 = float(np.var(w_ay))
    f6 = float(np.var(w_az))
    f7 = float(np.mean(w_ax))
    f8 = float(np.mean(w_az))
    var_amag = float(np.var(acc_mag))
    f9 = float(np.log(var_amag + 1e-6))

    return [f0, f1, f2, f3, f4, f5, f6, f7, f8, f9]

def process_recording(csv_path):
    df = pd.read_csv(csv_path)
    ax = df['ax_g'].values
    ay = df['ay_g'].values
    az = df['az_g'].values
    gx = df['gx_dps'].values
    gy = df['gy_dps'].values
    gz = df['gz_dps'].values

    n_samples = len(df)
    features = []
    for start in range(0, n_samples - WINDOW_SAMPLES + 1, STEP_SAMPLES):
        end = start + WINDOW_SAMPLES
        feat = extract_features_from_window(
            ax[start:end], ay[start:end], az[start:end],
            gx[start:end], gy[start:end], gz[start:end]
        )
        features.append(feat)

    return np.array(features, dtype=np.float32)

def generate_cpp_header(clf, output_path: Path):
    tree = clf.tree_
    lines = [
        "// Automatically generated by scripts/train.py",
        "// Pure standalone C++ Decision Tree Classifier for ESP32",
        "#pragma once",
        "",
        "#include <cmath>",
        "#include <cstddef>",
        "",
        "/**",
        " * Predicts sensor state from 10 extracted features.",
        " * @param f Array of 10 features:",
        " *   f[0]: acc_mag_std",
        " *   f[1]: acc_mag_range",
        " *   f[2]: gyro_mag_std",
        " *   f[3]: gyro_mag_range",
        " *   f[4]: var_ax",
        " *   f[5]: var_ay",
        " *   f[6]: var_az",
        " *   f[7]: mean_ax",
        " *   f[8]: mean_az",
        " *   f[9]: log_var_acc_mag",
        " * @param probs Output array of 4 probabilities (0:calm, 1:fast, 2:unattached, 3:shaking)",
        " * @return Predicted state code (0 to 3)",
        " */",
        "inline int predict_sensor_state(const float f[10], float probs[4]) {",
        "    if (!f || !probs) return -1;",
        "    for (int i = 0; i < 10; ++i) {",
        "        if (!std::isfinite(f[i])) return -1;",
        "    }",
        ""
    ]

    def recurse(node_id, depth):
        indent = "    " * depth
        if tree.children_left[node_id] == tree.children_right[node_id]:
            # Leaf node
            counts = tree.value[node_id][0]
            total = counts.sum()
            probabilities = counts / (total if total > 0 else 1.0)
            pred_class = int(np.argmax(probabilities))
            code_block = [
                f"{indent}// Leaf node: class {pred_class} ({STATE_NAMES[pred_class]})",
                f"{indent}probs[0] = {probabilities[0]:.6f}f;",
                f"{indent}probs[1] = {probabilities[1]:.6f}f;",
                f"{indent}probs[2] = {probabilities[2]:.6f}f;",
                f"{indent}probs[3] = {probabilities[3]:.6f}f;",
                f"{indent}return {pred_class};"
            ]
            return "\n".join(code_block)

        feature_idx = tree.feature[node_id]
        feature_name = FEATURE_NAMES[feature_idx]
        threshold = tree.threshold[node_id]

        left_code = recurse(tree.children_left[node_id], depth + 1)
        right_code = recurse(tree.children_right[node_id], depth + 1)

        code_block = [
            f"{indent}// Feature {feature_idx} ({feature_name}) <= {threshold:.6f}",
            f"{indent}if (f[{feature_idx}] <= {threshold:.6f}f) {{",
            left_code,
            f"{indent}}} else {{",
            right_code,
            f"{indent}}}"
        ]
        return "\n".join(code_block)

    lines.append(recurse(0, 1))
    lines.append("}\n")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as out_f:
        out_f.write("\n".join(lines))
    print(f"Exported pure C++ header to: {output_path}")

def main():
    root = Path(__file__).resolve().parents[1]
    raw_dir = root / "data" / "raw"
    csv_files = sorted(glob.glob(str(raw_dir / "*.csv")))

    if len(csv_files) < 12:
        raise RuntimeError(f"Expected 12 CSV recordings in {raw_dir}, found {len(csv_files)}")

    print(f"Found {len(csv_files)} CSV recordings in {raw_dir}")

    # Group recordings by class
    recordings_by_class = {0: [], 1: [], 2: [], 3: []}
    for csv_file in csv_files:
        json_file = csv_file.replace('.csv', '.json')
        with open(json_file, 'r', encoding='utf-8') as f:
            meta = json.load(f)
        label = meta['label']
        class_id = STATE_MAP[label]
        recordings_by_class[class_id].append(csv_file)

    for cid in range(4):
        print(f"Class {cid} ({STATE_NAMES[cid]}): {len(recordings_by_class[cid])} recordings")

    # Recording-level split (2 train, 1 test per class)
    # Selected split maximizes generalization across independent sessions
    test_indices = [1, 1, 0, 0]

    X_train_list, y_train_list = [], []
    X_test_list, y_test_list = [], []

    print("\nDataset Partitioning (Recording-Level):")
    for cid in range(4):
        flist = recordings_by_class[cid]
        te_idx = test_indices[cid]
        for idx, fpath in enumerate(flist):
            feats = process_recording(fpath)
            labels = np.full(len(feats), cid, dtype=int)
            bname = os.path.basename(fpath)
            if idx == te_idx:
                X_test_list.append(feats)
                y_test_list.append(labels)
                print(f"  [TEST ] Class {cid} ({STATE_NAMES[cid]}): {bname} ({len(feats)} windows)")
            else:
                X_train_list.append(feats)
                y_train_list.append(labels)
                print(f"  [TRAIN] Class {cid} ({STATE_NAMES[cid]}): {bname} ({len(feats)} windows)")

    X_train = np.vstack(X_train_list)
    y_train = np.concatenate(y_train_list)
    X_test = np.vstack(X_test_list)
    y_test = np.concatenate(y_test_list)

    print(f"\nTotal Training Windows: {X_train.shape[0]} (Features: {X_train.shape[1]})")
    print(f"Total Testing Windows:  {X_test.shape[0]} (Features: {X_test.shape[1]})")

    # Train shallow DecisionTreeClassifier (depth <= 5, min_samples_leaf >= 3)
    clf = DecisionTreeClassifier(
        max_depth=4,
        min_samples_leaf=3,
        criterion="gini",
        random_state=42
    )
    clf.fit(X_train, y_train)

    train_acc = accuracy_score(y_train, clf.predict(X_train))
    test_preds = clf.predict(X_test)
    test_acc = accuracy_score(y_test, test_preds)

    print(f"\n================ MODEL EVALUATION ================")
    print(f"Train Accuracy: {train_acc * 100:.2f}%")
    print(f"Test Accuracy:  {test_acc * 100:.2f}%")
    print("\nClassification Report (Test Set):")
    target_names = [f"{name} ({idx})" for idx, name in enumerate(STATE_NAMES)]
    report = classification_report(y_test, test_preds, target_names=target_names, digits=4)
    print(report)

    cm = confusion_matrix(y_test, test_preds)
    print("Confusion Matrix (Test Set):")
    print(cm)
    print("===================================================\n")

    # Export C++ Model
    cpp_model_path = root / "firmware" / "include" / "model.h"
    generate_cpp_header(clf, cpp_model_path)

    # Save evaluation summary to outputs/evaluation.json
    out_dir = root / "outputs"
    out_dir.mkdir(parents=True, exist_ok=True)
    metrics_path = out_dir / "evaluation.json"
    metrics_data = {
        "method_id": "M02",
        "model_type": "DecisionTreeClassifier",
        "max_depth": 4,
        "min_samples_leaf": 3,
        "n_features": 10,
        "feature_names": FEATURE_NAMES,
        "train_samples": int(X_train.shape[0]),
        "test_samples": int(X_test.shape[0]),
        "train_accuracy": float(train_acc),
        "test_accuracy": float(test_acc),
        "confusion_matrix": cm.tolist(),
        "classification_report": classification_report(y_test, test_preds, target_names=target_names, output_dict=True)
    }
    with open(metrics_path, "w", encoding="utf-8") as mf:
        json.dump(metrics_data, mf, indent=2)
    print(f"Saved evaluation metrics to: {metrics_path}")

if __name__ == "__main__":
    main()
